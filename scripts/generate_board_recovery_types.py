"""Generate the recovery TypeScript contracts from the canonical closed schemas.

Run with PYTHONPATH=src python scripts/generate_board_recovery_types.py [--check].
No Node, network access or runtime jsonschema dependency is required.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from eslams.contracts.board_recovery import board_recovery_contract_definitions

TARGET = (Path(__file__).resolve().parents[1]
          / "packages/core-contracts/src/generated/board-recovery.ts")


def generated_typescript() -> str:
    definitions = board_recovery_contract_definitions()

    def render(schema: dict[str, Any], *, root: str | None = None) -> str:
        for name, definition in definitions.items():
            if name != root and schema == definition:
                return name
        if "const" in schema:
            return json.dumps(schema["const"])
        if "enum" in schema:
            return " | ".join(json.dumps(item) for item in schema["enum"])
        kind = schema.get("type")
        if kind == "object" or "properties" in schema:
            result = "{ " + " ".join(
                f"{key}: {render(value)};" for key, value in schema["properties"].items()
            ) + " }"
            if "oneOf" in schema:
                result += " & (" + " | ".join(render(item) for item in schema["oneOf"]) + ")"
            return result
        if "oneOf" in schema:
            return " | ".join(render(item) for item in schema["oneOf"])
        if kind == "array":
            if "prefixItems" in schema:
                return "[" + ", ".join(render(item) for item in schema["prefixItems"]) + "]"
            raise ValueError("unhandled array shape")
        if isinstance(kind, list):
            return " | ".join(render({"type": item}) for item in kind)
        if kind in {"integer", "number"}:
            return "number"
        if kind in {"string", "boolean", "null"}:
            return str(kind)
        raise ValueError("unhandled recovery schema")

    lines = [
        "// Generated by scripts/generate_board_recovery_types.py. Do not edit.",
        "// Structural wire types do not prove source authenticity or confer scoring eligibility.",
        "",
    ]
    for name, definition in definitions.items():
        if definition.get("type") == "object" and "oneOf" not in definition:
            lines.append(f"export interface {name} {{")
            for key, value in definition["properties"].items():
                lines.append(f"  {key}: {render(value)};")
            lines.extend(["}", ""])
        else:
            lines.extend([f"export type {name} = {render(definition, root=name)};", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generated_typescript()
    if args.check:
        if TARGET.read_text(encoding="utf-8") != expected:
            raise SystemExit("generated recovery contracts are stale")
    else:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
