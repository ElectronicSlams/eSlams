"""Generate only board continuation TypeScript and compile fixtures from JSON Schemas.

Use --write to regenerate; default/--check reports drift without modifying files.
Run from the repository with its src package available, like other repo scripts.
"""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path
from typing import Any

from eslams.contracts.board_continuation import (
    board_continuation_examples,
    board_continuation_schemas,
)
from eslams.contracts.versions import (
    BOARD_CONTINUATION_CHILD_EXECUTION_SCHEMA_VERSION as CHILD,
)
from eslams.contracts.versions import (
    BOARD_CONTINUATION_ENGINE_SCHEMA_VERSION as ENGINE,
)
from eslams.contracts.versions import (
    BOARD_CONTINUATION_LINEAGE_SCHEMA_VERSION as LINEAGE,
)
from eslams.contracts.versions import (
    BOARD_CONTINUATION_SCHEMA_VERSION as DESCRIPTOR,
)

ROOT = Path(__file__).resolve().parents[1]
HEADER = "// Generated by scripts/generate_board_continuation_types.py; do not edit.\n"


def generated_files() -> dict[Path, str]:
    schemas = board_continuation_schemas()
    descriptor = schemas[DESCRIPTOR]
    execution = descriptor["properties"]["execution"]
    player = copy.deepcopy(execution["properties"]["players"]["prefixItems"][0])
    player["properties"]["seat"] = {"enum": ["player_1", "player_2"]}
    lineage = schemas[LINEAGE]
    named = {
        "BoardContinuationArena": execution["properties"]["arenaSlug"],
        "BoardContinuationPlayer": player,
        "BoardContinuationSource": descriptor["properties"]["source"],
        "BoardContinuationPrefix": descriptor["properties"]["prefix"],
        "BoardContinuationExecution": execution,
        "BoardContinuationDescriptor": descriptor,
        "BoardContinuationChildExecution": schemas[CHILD],
        "BoardContinuationEngine": schemas[ENGINE],
        "BoardContinuationLedgerSegment": lineage["properties"]["historicalLedger"]["properties"][
            "segments"]["items"],
        "BoardContinuationLineage": lineage,
    }

    def render(schema: dict[str, Any], *, root: bool = False, indent: int = 0) -> str:
        if not root:
            for name, known in named.items():
                if schema == known:
                    return name
        if "$ref" in schema:
            assert schema["$ref"] == "#/$defs/lineage"
            return "BoardContinuationLineage"
        if "const" in schema:
            return json.dumps(schema["const"])
        if "enum" in schema:
            return " | ".join(json.dumps(value) for value in schema["enum"])
        if "anyOf" in schema:
            return " | ".join(render(item, indent=indent) for item in schema["anyOf"])
        kind = schema["type"]
        if kind == "array":
            if "prefixItems" in schema:
                return "[" + ", ".join(render(item, indent=indent)
                                        for item in schema["prefixItems"]) + "]"
            return "Array<" + render(schema["items"], indent=indent) + ">"
        if kind == "object":
            pad = "  " * (indent + 1)
            rows = ["{"]
            for key, value in schema["properties"].items():
                optional = "" if key in schema.get("required", []) else "?"
                rows.append(f"{pad}{key}{optional}: {render(value, indent=indent + 1)};")
            if schema.get("additionalProperties") is True:
                rows.append(pad + "[key: string]: unknown;")
            return "\n".join(rows + ["  " * indent + "}"])
        return {"string": "string", "integer": "number", "number": "number",
                "boolean": "boolean", "null": "null"}[kind]

    output = HEADER + "/** Private custody shapes; typing does not establish source admission. */\n"
    for name, schema in named.items():
        value = render(schema, root=True)
        output += (f"export interface {name} {value}\n" if schema.get("type") == "object"
                   else f"export type {name} = {value};\n")
    examples = board_continuation_examples()
    fixture = HEADER + 'import type {\n'
    fixture += "\n".join("  " + name + "," for name in named)
    fixture += '} from "../src/generated/board-continuation.js";\n\n'
    for index, (version, name) in enumerate(((DESCRIPTOR, "BoardContinuationDescriptor"),
                                            (CHILD, "BoardContinuationChildExecution"),
                                            (ENGINE, "BoardContinuationEngine"),
                                            (LINEAGE, "BoardContinuationLineage"))):
        example = json.dumps(examples[version], indent=2)
        fixture += f"export const example{index}: {name} = {example};\n"
    fixture += '''
// @ts-expect-error chess must not enter the board namespace
const wrongArena: BoardContinuationArena = "chess";
// @ts-expect-error installed engine claims are not a board preview identity
const installed: BoardContinuationEngine["coreRef"] = "immutable-release";
// @ts-expect-error first seat ordering is part of the exact execution contract
const wrongSeat: BoardContinuationExecution["players"][0]["seat"] = "player_2";
'''
    return {ROOT / "packages/core-contracts/src/generated/board-continuation.ts": output,
            ROOT / "packages/core-contracts/test/board-continuation.ts": fixture}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write and args.check:
        parser.error("choose --write or --check")
    stale = []
    for path, content in generated_files().items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        elif not path.is_file() or path.read_text() != content:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        print("Board continuation TypeScript drift: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
