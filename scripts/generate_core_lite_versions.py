"""Generate Core-lite response metadata from authoritative Python contracts."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from eslams.contracts.versions import (
    CORE_ACTION_SCHEMA_VERSION,
    CORE_CONTRACT_VERSION,
    CORE_PACKAGE_VERSION,
    CORE_PROMPT_VERSION,
    CORE_REPLAY_EVENT_SCHEMA_VERSION,
)

TARGET = Path(__file__).resolve().parents[1] / "packages/core-lite/src/versions.ts"


def generated_typescript() -> str:
    versions = {
        "coreVersion": CORE_PACKAGE_VERSION,
        "coreContractVersion": CORE_CONTRACT_VERSION,
        "rulesetVersion": "standard",
        "promptVersion": CORE_PROMPT_VERSION,
        "actionSchemaVersion": CORE_ACTION_SCHEMA_VERSION,
        "replaySchemaVersion": CORE_REPLAY_EVENT_SCHEMA_VERSION,
    }
    return ("// Generated by scripts/generate_core_lite_versions.py. Do not edit.\n"
            + "export const RESPONSE_VERSIONS = " + json.dumps(versions, indent=2)
            + " as const;\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generated_typescript()
    if args.check:
        if TARGET.read_text(encoding="utf-8") != expected:
            raise SystemExit("generated Core-lite versions are stale")
    else:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
