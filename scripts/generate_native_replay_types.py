"""Generate public native replay TypeScript and contained no-secret example."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from eslams.contracts.native_replay import native_contract_definitions
from eslams.hashing import canonical_json
from eslams.native_artifact import verify_native_replay
from eslams.native_runner import NativeProfile, run_local_native

ROOT = Path(__file__).resolve().parents[1]
TYPES = ROOT / "packages/core-contracts/src/generated/native-replay.ts"
EXAMPLE = ROOT / "fixtures/native/rock-paper-scissors.json"


def generated_typescript() -> str:
    def render(schema: dict[str, Any]) -> str:
        if "const" in schema:
            return json.dumps(schema["const"])
        if "enum" in schema:
            return " | ".join(json.dumps(v) for v in schema["enum"])
        if "anyOf" in schema:
            return " | ".join(dict.fromkeys(render(x) for x in schema["anyOf"]))
        if schema["type"] == "array":
            return "Array<" + render(schema["items"]) + ">"
        if schema["type"] == "object":
            if not schema["properties"]:
                return "Record<string, never>"
            return "{ " + " ".join(
                f"{k}: {render(v)};" for k, v in schema["properties"].items()
            ) + " }"
        if schema["type"] == "integer":
            return "number"
        return str(schema["type"])

    lines = [
        "// Generated by scripts/generate_native_replay_types.py. Do not edit.",
        "// Types describe parsed public JSON; use Core to verify the ZIP and event order.",
        "",
    ]
    for name, obj in native_contract_definitions().items():
        lines.append("export interface " + name + " {")
        for key, rule in obj["properties"].items():
            if key == "game_facts":
                lines.append("  game_facts:")
                cases = dict.fromkeys(render(x) for x in rule["anyOf"])
                lines.extend("    | " + x + (";" if i == len(cases) - 1 else "")
                             for i, x in enumerate(cases))
            else:
                lines.append(f"  {key}: {render(rule)};")
        lines.extend(["}", ""])
    return "\n".join(lines)


def generated_example() -> str:
    trace = run_local_native(NativeProfile("rock-paper-scissors"), "native-example")
    proof = verify_native_replay(trace.contents)
    return canonical_json({"manifest": proof.manifest, "events": proof.events}) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    for path, text in ((TYPES, generated_typescript()), (EXAMPLE, generated_example())):
        if check:
            if path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"stale generated file: {path.name}")
        else:
            path.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
